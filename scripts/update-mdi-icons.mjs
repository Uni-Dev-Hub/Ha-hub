// Regenerates contents/code/mdi_icons.mjs from the Material Design Icons web
// font CSS. Home Assistant names entity icons the way this font spells them
// ("mdi:lightbulb"), so a name -> codepoint map plus the bundled TTF in
// contents/fonts/ lets the tiles draw exactly the icons the user picked in HA.
//
//   node scripts/update-mdi-icons.mjs [version]
//
// When the version changes, download the matching font and licence too:
//   curl -L -o contents/fonts/materialdesignicons-webfont.ttf \
//     https://cdn.jsdelivr.net/npm/@mdi/font@<version>/fonts/materialdesignicons-webfont.ttf
//   curl -L -o contents/fonts/LICENSE \
//     https://cdn.jsdelivr.net/npm/@mdi/font@<version>/LICENSE

import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const version = process.argv[2] || "7.4.47";
const cssUrl = `https://cdn.jsdelivr.net/npm/@mdi/font@${version}/css/materialdesignicons.css`;

const response = await fetch(cssUrl);
if (!response.ok) {
    console.error(`could not fetch ${cssUrl}: HTTP ${response.status}`);
    process.exit(1);
}
const css = await response.text();

const icons = new Map();
for (const [, name, hex] of css.matchAll(/^\.mdi-([a-z0-9][a-z0-9-]*)::before\s*\{\s*content:\s*"\\([0-9A-Fa-f]+)"/gm)) {
    icons.set(name, parseInt(hex, 16));
}
if (icons.size < 1000) {
    console.error(`only found ${icons.size} icons in ${cssUrl}, the CSS format must have changed`);
    process.exit(1);
}

const names = [...icons.keys()].sort();
const entries = names.map((name) => `    "${name}": ${icons.get(name)}`);
// Four per line keeps the generated file browsable without being 7000 lines.
const rows = [];
for (let i = 0; i < entries.length; i += 4) {
    rows.push(entries.slice(i, i + 4).join(", ") + ",");
}

const source = `// Generated by scripts/update-mdi-icons.mjs from @mdi/font ${version} - do not edit.
//
// Home Assistant stores entity icons as Material Design Icons names
// ("mdi:ceiling-light"). QML cannot load those through the icon theme, so the
// glyphs are drawn from the bundled font in contents/fonts/ and this table is
// what turns a name into a codepoint of that font.

var MDI_CODEPOINTS = {
${rows.join("\n")}
};

// Codepoint of an MDI name, 0 when the font does not have such a glyph.
function mdiCodepoint(name) {
    if (!name) return 0;
    var value = MDI_CODEPOINTS[name.toString().trim().toLowerCase()];
    return value === undefined ? 0 : value;
}

// The character to render for an MDI name, "" when it is unknown.
function mdiGlyph(name) {
    var codepoint = mdiCodepoint(name);
    return codepoint ? String.fromCodePoint(codepoint) : "";
}

export { MDI_CODEPOINTS, mdiCodepoint, mdiGlyph };
`;

writeFileSync(join(ROOT, "contents/code/mdi_icons.mjs"), source);
console.log(`wrote contents/code/mdi_icons.mjs with ${icons.size} icons (@mdi/font ${version})`);
